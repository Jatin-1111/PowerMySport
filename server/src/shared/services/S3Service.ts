  constructor() {
    // Load environment variables first
    this.region = process.env.AWS_REGION || "ap-south-1";
    this.documentsBucket = process.env.AWS_S3_DOCUMENTS_BUCKET || "powermysport-documents";
    this.imagesBucket = process.env.AWS_S3_IMAGES_BUCKET || "powermysport-images";
    this.childVideosBucket = process.env.AWS_S3_CHILD_VIDEOS_BUCKET || "powermysport-child-videos";

    // This class is constructed in a dozen modules, several at import time, so
    // logging per-instance printed the same three lines five times at boot.
    bootFactOnce("s3", `${this.region} · images=${this.imagesBucket} docs=${this.documentsBucket}`);

    const clientConfig: S3ClientConfig = {
      region: this.region,
    };

    if (process.env.AWS_ACCESS_KEY_ID && process.env.AWS_SECRET_ACCESS_KEY) {
      clientConfig.credentials = {
        accessKeyId: process.env.AWS_ACCESS_KEY_ID,
        secretAccessKey: process.env.AWS_SECRET_ACCESS_KEY,
      };
    }

    this.s3Client = new S3Client(clientConfig);
  }

  /**
   * Content types we accept for uploads. Anything else (executables, HTML,
   * SVG, arbitrary octet-streams) is rejected before we sign a URL, so the
   * client cannot have S3 store an object with an attacker-chosen type.
   */
  private static readonly ALLOWED_UPLOAD_CONTENT_TYPES = new Set([
    "image/jpeg",
    "image/jpg",
    "image/png",
    "image/webp",
    "image/gif",
    "image/heic",
    "image/heif",
    "application/pdf",
  ]);

  /**
   * Validate the client-supplied content type against the allowlist and return
   * a sanitized file extension. The object KEY is always server-generated by
   * the callers, so only the (cosmetic) extension is derived from fileName —
   * and it is stripped to a short alphanumeric token to avoid surprises.
   */
  private resolveSafeExtension(fileName: string, contentType: string): string {
    if (!contentType || !S3Service.ALLOWED_UPLOAD_CONTENT_TYPES.has(contentType.toLowerCase())) {
      throw new Error(`Unsupported upload content type: ${contentType || "unknown"}`);
    }
    const ext = (fileName.split(".").pop() || "")
      .toLowerCase()
      .replace(/[^a-z0-9]/g, "")
      .slice(0, 5);
    return ext || "bin";
  }

  /**
   * Generate presigned upload URL for document uploads
   * @param fileName - Original file name
   * @param contentType - MIME type (e.g., application/pdf, image/jpeg)
   * @param documentType - Type of document for folder organization
   * @returns Presigned URL and metadata
   */
  async generateDocumentUploadUrl(
    fileName: string,
    contentType: string,
    documentType:
      | "OWNERSHIP_PROOF"
      | "BUSINESS_REGISTRATION"
      | "TAX_DOCUMENT"
      | "INSURANCE"
      | "CERTIFICATE"
      | "panDocument"
      | "gstDocument",
    venueId: string
  ): Promise<UploadUrlResponse> {
    const fileExtension = this.resolveSafeExtension(fileName, contentType);
    const sanitizedFileName = `${documentType.toLowerCase()}_${Date.now()}.${fileExtension}`;
    const key = `venues/${venueId}/documents/${sanitizedFileName}`;

    const putCommand = new PutObjectCommand({
      Bucket: this.documentsBucket,
      Key: key,
      ContentType: contentType,
    });

    const uploadUrl = await getSignedUrl(this.s3Client, putCommand, {
      expiresIn: 3600, // 1 hour
    });

    // Generate presigned download URL (valid for 7 days) for private bucket
    const getCommand = new GetObjectCommand({
      Bucket: this.documentsBucket,
      Key: key,
    });

    const downloadUrl = await getSignedUrl(this.s3Client, getCommand, {
      expiresIn: 604800, // 7 days
    });

    return {
      uploadUrl,
      downloadUrl,
      fileName: sanitizedFileName,
      key,
    };
  }

